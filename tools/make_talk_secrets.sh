#!/bin/sh
# Writes firmware/main/app/secrets_talk.h (gitignored: "secrets*") with the
# pet-bridge address and the pet's token, copied straight from the server. Run it
# once, and again if the token on the server is ever changed.
set -e
cd "$(dirname "$0")/.."
SERVER=${SERVER:-192.168.1.50}
T=$(ssh "${SERVER_USER:-user}@$SERVER" cat pet-bridge/pet.token)
umask 077
printf '// Generated by tools/make_talk_secrets.sh - never commit.\n#pragma once\n#define PET_BRIDGE_URL "http://%s:8090"\n#define PET_TOKEN "%s"\n' \
  "$SERVER" "$T" > firmware/main/app/secrets_talk.h
echo "wrote firmware/main/app/secrets_talk.h"
